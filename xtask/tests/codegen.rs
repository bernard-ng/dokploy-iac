#[test]
fn codegen_normalizes_all_604_auth_references_without_changing_response_contracts() {
    let directory = tempfile::tempdir().expect("temporary directory should exist");
    let repository_root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask should be below the repository root");
    let source = repository_root.join("openapi/dokploy.json");
    let original_bytes = fs::read(&source).expect("vendored contract should be readable");
    let original: Value =
        serde_json::from_slice(&original_bytes).expect("vendored contract should be valid JSON");
    let original_responses = operation_responses(&original);
    let observations = Arc::new(Mutex::new(None));
    let generator = InspectingGenerator {
        observations: Arc::clone(&observations),
    };
    let paths = CodegenPaths {
        source: source.clone(),
        committed_output: directory.path().join("generated"),
        scratch_parent: directory.path().join("scratch"),
        expected_warning_count: 0,
    };

    let report = run_codegen(&generator, &paths, CodegenMode::Write)
        .expect("full contract generation should succeed");

    let observations = observations
        .lock()
        .expect("observations lock should be available")
        .take()
        .expect("generator should inspect the normalized contract");
    assert_eq!(report.operation_count, 604);
    assert_eq!(report.normalized_security_references, 604);
    let generated_metadata = fs::read_to_string(paths.committed_output.join("metadata.rs"))
        .expect("full endpoint metadata should be generated");
    assert_eq!(generated_metadata.matches("pub const ").count(), 604);
    assert_eq!(observations.operation_count, 604);
    assert_eq!(observations.api_key_references, 604);
    assert_eq!(observations.authorization_references, 0);
    assert_eq!(observations.responses, original_responses);
    assert_eq!(
        fs::read(source).expect("vendored contract should remain readable"),
        original_bytes
    );
}

struct WrongVersionGenerator;

impl CodeGenerator for WrongVersionGenerator {
    fn version(&self) -> Result<String, std::io::Error> {
        Ok("oas3-gen 0.29.0".to_owned())
    }

    fn generate(&self, _source: &Path, _output: &Path) -> Result<GeneratorOutput, std::io::Error> {
        panic!("generation must not run with an unpinned version");
    }
}

struct InspectingGenerator {
    observations: Arc<Mutex<Option<ContractObservations>>>,
}

impl CodeGenerator for InspectingGenerator {
    fn version(&self) -> Result<String, std::io::Error> {
        Ok("oas3-gen 0.28.0".to_owned())
    }

    fn generate(&self, source: &Path, output: &Path) -> Result<GeneratorOutput, std::io::Error> {
        let normalized: Value = serde_json::from_slice(&fs::read(source)?)
            .map_err(|error| std::io::Error::other(error.to_string()))?;
        let operation_count = operation_count(&normalized);
        let api_key_references = security_reference_count(&normalized, "apiKey");
        let authorization_references = security_reference_count(&normalized, "Authorization");
        self.observations
            .lock()
            .expect("observations lock should be available")
            .replace(ContractObservations {
                operation_count,
                api_key_references,
                authorization_references,
                responses: operation_responses(&normalized),
            });

        FixtureGenerator {
            operations: operation_count,
        }
        .generate(source, output)
    }
}

struct ContractObservations {
    operation_count: usize,
    api_key_references: usize,
    authorization_references: usize,
    responses: Vec<(String, String, Value)>,
}

fn operations(contract: &Value) -> impl Iterator<Item = (&String, &String, &Value)> {
    contract["paths"]
        .as_object()
        .into_iter()
        .flat_map(|paths| paths.iter())
        .flat_map(|(path, item)| {
            item.as_object().into_iter().flat_map(move |item| {
                item.iter().filter_map(move |(method, operation)| {
                    [
                        "delete", "get", "head", "options", "patch", "post", "put", "trace",
                    ]
                    .contains(&method.as_str())
                    .then_some((path, method, operation))
                })
            })
        })
}

fn operation_count(contract: &Value) -> usize {
    operations(contract).count()
}

fn security_reference_count(contract: &Value, name: &str) -> usize {
    operations(contract)
        .flat_map(|(_, _, operation)| operation["security"].as_array().into_iter().flatten())
        .filter(|requirement| requirement.get(name).is_some())
        .count()
}

fn operation_responses(contract: &Value) -> Vec<(String, String, Value)> {
    operations(contract)
        .map(|(path, method, operation)| {
            (path.clone(), method.clone(), operation["responses"].clone())
        })
        .collect()
}

struct CodegenFixture {
    _directory: TempDir,
    paths: CodegenPaths,
}

impl CodegenFixture {
    fn new(operation_count: usize) -> Self {
        let directory = tempfile::tempdir().expect("temporary directory should exist");
        let source = directory.path().join("dokploy.json");
        let paths = (0..operation_count)
            .map(|index| {
                format!(
                    r#""/fixture.{index}": {{"get": {{"operationId": "fixture-{index}", "security": [{{"Authorization": []}}], "responses": {{"200": {{"description": "ok", "content": {{"application/json": {{"schema": {{"type": "object", "properties": {{}}, "additionalProperties": false}}}}}}}}}}}}}}"#,
                )
            })
            .collect::<Vec<_>>()
            .join(",");
        fs::write(
            &source,
            format!(
                r#"{{"openapi":"3.1.0","info":{{"title":"Fixture","version":"1"}},"security":[{{"apiKey":[]}}],"paths":{{{paths}}},"components":{{"securitySchemes":{{"apiKey":{{"type":"apiKey","in":"header","name":"x-api-key"}}}}}}}}"#,
            ),
        )
        .expect("fixture contract should be written");

        let paths = CodegenPaths {
            source,
            committed_output: directory.path().join("generated"),
            scratch_parent: directory.path().join("scratch"),
            expected_warning_count: 0,
        };

        Self {
            _directory: directory,
            paths,
        }
    }
}
