use std::{
    fs,
    path::Path,
    sync::{Arc, Mutex},
};

use serde_json::Value;
use tempfile::TempDir;
use xtask::{CodeGenerator, CodegenError, CodegenMode, CodegenPaths, GeneratorOutput, run_codegen};

const GENERATED_HEADER: &str = "// @generated by `cargo xtask codegen`; DO NOT EDIT.\n";

struct FixtureGenerator {
    operations: usize,
}

impl CodeGenerator for FixtureGenerator {
    fn version(&self) -> Result<String, std::io::Error> {
        Ok("oas3-gen 0.28.0".to_owned())
    }

    fn generate(&self, source: &Path, output: &Path) -> Result<GeneratorOutput, std::io::Error> {
        assert!(source.ends_with("dokploy.json"));
        fs::create_dir_all(output)?;
        fs::write(output.join("mod.rs"), "pub mod generated_fixture;\n")?;
        fs::write(output.join("types.rs"), "pub struct Fixture;\n")?;

        let methods = (0..self.operations)
            .map(|index| format!("    /// * Path: `GET /fixture.{index}`\n    pub async fn operation_{index}() {{}}\n"))
            .collect::<String>();
        fs::write(output.join("client.rs"), methods)?;

        Ok(GeneratorOutput::default())
    }
}

#[test]
fn codegen_writes_a_nonempty_generated_snapshot_with_do_not_edit_headers() {
    let fixture = CodegenFixture::new(1);

    let report = run_codegen(
        &FixtureGenerator { operations: 1 },
        &fixture.paths,
        CodegenMode::Write,
    )
    .expect("generation should succeed");

    assert_eq!(report.operation_count, 1);
    assert_eq!(report.file_count, 4);
    assert_eq!(report.normalized_security_references, 1);

    for file_name in ["client.rs", "metadata.rs", "mod.rs", "types.rs"] {
        let contents = fs::read_to_string(fixture.paths.committed_output.join(file_name))
            .expect("generated file should be written");
        assert!(contents.starts_with(GENERATED_HEADER));
    }
}

#[test]
fn codegen_derives_endpoint_metadata_from_the_openapi_contract() {
    let fixture = CodegenFixture::new(1);

    let report = run_codegen(
        &FixtureGenerator { operations: 1 },
        &fixture.paths,
        CodegenMode::Write,
    )
    .expect("generation should succeed");

    let metadata = fs::read_to_string(fixture.paths.committed_output.join("metadata.rs"))
        .expect("endpoint metadata should be generated");
    assert_eq!(report.file_count, 4);
    assert!(metadata.contains("pub const FIXTURE_0: Endpoint"));
    assert!(metadata.contains("EndpointMethod::Get"));
    assert!(metadata.contains(r#"Endpoint::new("fixture-0", "fixture.0""#));
    assert!(metadata.contains(r#""fixture.0" => Some(FIXTURE_0)"#));
}

#[test]
fn codegen_rejects_an_empty_generated_operation_set_without_replacing_the_snapshot() {
    let fixture = CodegenFixture::new(1);
    fs::create_dir_all(&fixture.paths.committed_output).expect("output directory should exist");
    let existing = fixture.paths.committed_output.join("client.rs");
    fs::write(&existing, "existing snapshot\n").expect("existing snapshot should be written");

    let error = run_codegen(
        &FixtureGenerator { operations: 0 },
        &fixture.paths,
        CodegenMode::Write,
    )
    .expect_err("empty generated output must fail");

    assert!(matches!(
        error,
        CodegenError::EmptyGeneratedOperations { expected: 1 }
    ));
    assert_eq!(
        fs::read_to_string(existing).expect("existing snapshot should remain readable"),
        "existing snapshot\n"
    );
}

#[test]
fn codegen_rejects_a_partial_generated_operation_set() {
    let fixture = CodegenFixture::new(2);

    let error = run_codegen(
        &FixtureGenerator { operations: 1 },
        &fixture.paths,
        CodegenMode::Write,
    )
    .expect_err("partial generated output must fail");

    assert!(matches!(
        error,
        CodegenError::OperationCountMismatch {
            expected: 2,
            actual: 1
        }
    ));
    assert!(!fixture.paths.committed_output.exists());
}

#[test]
fn codegen_check_reports_drift_without_modifying_the_snapshot() {
    let fixture = CodegenFixture::new(1);
    let generator = FixtureGenerator { operations: 1 };
    run_codegen(&generator, &fixture.paths, CodegenMode::Write)
        .expect("initial snapshot should be written");
    let drifted = fixture.paths.committed_output.join("metadata.rs");
    fs::write(&drifted, "manual edit\n").expect("snapshot should be modified for the fixture");

    let error = run_codegen(&generator, &fixture.paths, CodegenMode::Check)
        .expect_err("drifted generated output must fail the check");

    assert!(matches!(error, CodegenError::Drift(paths) if paths == vec![drifted.clone()]));
    assert_eq!(
        fs::read_to_string(drifted).expect("drifted file should remain readable"),
        "manual edit\n"
    );
}

