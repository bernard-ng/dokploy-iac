#[test]
fn codegen_rejects_the_wrong_generator_version_before_writing_output() {
    let fixture = CodegenFixture::new(1);

    let error = run_codegen(&WrongVersionGenerator, &fixture.paths, CodegenMode::Write)
        .expect_err("an unpinned generator must fail");

    assert!(matches!(
        error,
        CodegenError::GeneratorVersion { expected, actual }
            if expected == "oas3-gen 0.28.0" && actual == "oas3-gen 0.29.0"
    ));
    assert!(!fixture.paths.committed_output.exists());
}

