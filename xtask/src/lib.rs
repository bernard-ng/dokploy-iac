pub fn repository_imperative_paths(repository_root: &Path) -> ImperativeCodegenPaths {
    ImperativeCodegenPaths {
        source: repository_root.join("openapi/dokploy.json"),
        committed_output: repository_root.join("crates/dokploy-cli/src/imperative_generated.rs"),
        scratch_parent: repository_root.join("target/codegen"),
    }
}

#[must_use]
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask must remain directly below the repository root")
        .to_path_buf()
}
