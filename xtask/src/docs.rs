//! Deterministic user documentation generated from specs and Clap.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use clap::CommandFactory;
use dokploy_cli::cli::Cli;
use dokploy_spec::{Field, KindSpec, SpecRegistry};
use thiserror::Error;

/// Whether generated documentation is written or compared with the repository.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DocsMode {
    Write,
    Check,
}

/// Counts produced by documentation generation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct DocsReport {
    pub kind_count: usize,
    pub command_count: usize,
}

#[derive(Debug, Error)]
pub enum DocsError {
    #[error("cannot load kind specs: {0}")]
    Specs(#[from] dokploy_spec::LoadError),
    #[error("cannot read or write {path}: {source}")]
    Io {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("generated documentation differs: {0}")]
    Drift(PathBuf),
}

/// Generates the resource reference and CLI usage pages.
pub fn run_docs(root: &Path, mode: DocsMode) -> Result<DocsReport, DocsError> {
    let specs = dokploy_spec::load_dir(&root.join("specs"))?;
    let reference = reference(&specs);
    let (usage, command_count) = usage();
    let directory = root.join("docs/generated");
    if mode == DocsMode::Write {
        fs::create_dir_all(&directory).map_err(|source| DocsError::Io {
            path: directory.clone(),
            source,
        })?;
    }
    emit(&directory.join("resource-reference.md"), &reference, mode)?;
    emit(&directory.join("cli-usage.md"), &usage, mode)?;

    Ok(DocsReport {
        kind_count: specs.kinds().count(),
        command_count,
    })
}

fn emit(path: &Path, expected: &str, mode: DocsMode) -> Result<(), DocsError> {
    match mode {
        DocsMode::Write => fs::write(path, expected).map_err(|source| DocsError::Io {
            path: path.to_path_buf(),
            source,
        }),
        DocsMode::Check => {
            let actual = fs::read_to_string(path).map_err(|source| DocsError::Io {
                path: path.to_path_buf(),
                source,
            })?;
            if actual == expected {
                Ok(())
            } else {
                Err(DocsError::Drift(path.to_path_buf()))
            }
        }
    }
}

fn reference(specs: &SpecRegistry) -> String {
    let mut text = String::from(
        "# Resource reference\n\n<!-- Generated by `cargo xtask docs`. Do not edit. -->\n\n",
    );
    text.push_str(
        "This page lists the resource fields accepted by version 2 project and settings documents.\n\n",
    );
    text.push_str("| Kind | Title | Scope | Section | Class | Coverage |\n");
    text.push_str("|---|---|---|---|---|---|\n");
    for spec in specs.kinds() {
        let _ = writeln!(
            text,
            "| `{}` | {} | `{:?}` | `{}` | `{:?}` | `{:?}` |",
            spec.kind, spec.title, spec.scope, spec.section, spec.class, spec.coverage
        );
    }
    for spec in specs.kinds() {
        render_kind(&mut text, spec);
    }

    text
}

fn render_kind(text: &mut String, spec: &KindSpec) {
    let _ = writeln!(text, "\n## {} (`{}`)\n", spec.title, spec.kind);
    if !spec.parents.is_empty() {
        let parents = spec
            .parents
            .iter()
            .map(|parent| format!("`{parent}`"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(text, "Parents: {parents}.\n");
    }
    text.push_str("| Field | API field | Type | Class | Mutability | Description |\n");
    text.push_str("|---|---|---|---|---|---|\n");
    for (name, field) in &spec.fields {
        render_field(text, name, name, field);
    }
}

fn render_field(text: &mut String, path: &str, default_api: &str, field: &Field) {
    let api = field.api.as_deref().unwrap_or(default_api);
    let description = field.doc.as_deref().unwrap_or("");
    let _ = writeln!(
        text,
        "| `{}` | `{}` | `{}` | `{:?}` | `{:?}` | {} |",
        escape(path),
        escape(api),
        escape(&field.ty),
        field.class,
        field.mutability,
        escape(description)
    );
    for (name, member) in &field.members {
        render_field(text, &format!("{path}.{name}"), name, member);
    }
    for (arm, members) in &field.arms {
        for (name, member) in members {
            render_field(text, &format!("{path}.{arm}.{name}"), name, member);
        }
    }
}

fn usage() -> (String, usize) {
    let mut root = Cli::command();
    let mut text =
        String::from("# CLI usage\n\n<!-- Generated by `cargo xtask docs`. Do not edit. -->\n\n");
    text.push_str(
        "Global connection values resolve in this order: command flags, environment variables, then the selected context.\n\n",
    );
    render_help(&mut text, "dokploy", &mut root);
    let mut command_count = 1_usize;
    for mut command in root.get_subcommands().cloned() {
        let name = command.get_name().to_owned();
        render_help(&mut text, &format!("dokploy {name}"), &mut command);
        command_count += 1;
    }

    (text, command_count)
}

fn render_help(text: &mut String, heading: &str, command: &mut clap::Command) {
    command.set_bin_name(heading);
    let _ = writeln!(text, "## `{heading}`\n\n```text");
    let help = command.render_long_help().to_string();
    text.push_str(help.trim_end());
    text.push_str("\n```\n\n");
}

fn escape(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}
